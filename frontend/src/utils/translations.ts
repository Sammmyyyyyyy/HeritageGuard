// Localized Date Formatter (e.g., "31 Aug" -> "31 अगस्त", "1 Sep" -> "1 सितंबर")
export function formatDateLocalized(formattedDate: string, lang: Language): string {
  if (lang === 'en' || !formattedDate) return formattedDate;
  const months: Record<string, string> = {
    'Jan': 'जनवरी',
    'Feb': 'फ़रवरी',
    'Mar': 'मार्च',
    'Apr': 'अप्रैल',
    'May': 'मई',
    'Jun': 'जून',
    'Jul': 'जुलाई',
    'Aug': 'अगस्त',
    'Sep': 'सितंबर',
    'Oct': 'अक्टूबर',
    'Nov': 'नवंबर',
    'Dec': 'दिसंबर'
  };
  let result = formattedDate;
  Object.entries(months).forEach(([enM, hiM]) => {
    result = result.replace(new RegExp(`\\b${enM}\\b`, 'gi'), hiM);
  });
  return result;
}

